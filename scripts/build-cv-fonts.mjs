// CV fonts (OFL, @fontsource): copies the woff2 subsets the CV renderer needs and writes the two generated modules.
//   apps/web/public/cv-fonts/*.woff2                          web: the renderer gets "/cv-fonts/<file>" URLs
//   packages/core/src/career/cv-fonts.manifest.ts             family / weight / subset / unicode-range per file
//   apps/mobile/src/features/career/cv-fonts.generated.ts     mobile: base64 data URIs (expo-print has no web server)
// Usage: node scripts/build-cv-fonts.mjs   (re-run after bumping an @fontsource package)
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FAMILIES = ["inter", "noto-sans", "noto-serif"];
const WEIGHTS = [400, 700];
// latin + latin-ext cover az/tr (ə Ə ğ ş ç ö ü ı İ), cyrillic covers ru.
const SUBSETS = ["latin", "latin-ext", "cyrillic"];

const faces = [];
for (const family of FAMILIES) {
  const dir = path.join(root, "node_modules/@fontsource", family);
  for (const weight of WEIGHTS) {
    const css = readFileSync(path.join(dir, `${weight}.css`), "utf8");
    for (const subset of SUBSETS) {
      const file = `${family}-${subset}-${weight}-normal.woff2`;
      const block = css.split("/* ").find((b) => b.startsWith(`${family}-${subset}-${weight}-normal */`));
      const range = block && /unicode-range:\s*([^;]+);/.exec(block)?.[1]?.trim();
      if (!range) throw new Error(`no @font-face for ${file}`);
      faces.push({ family, weight, subset, file, unicodeRange: range, abs: path.join(dir, "files", file) });
    }
  }
}

const webDir = path.join(root, "apps/web/public/cv-fonts");
mkdirSync(webDir, { recursive: true });
for (const f of faces) copyFileSync(f.abs, path.join(webDir, f.file));

const banner = "// GENERATED by scripts/build-cv-fonts.mjs - do not edit.\n";
const manifest = faces.map(({ family, weight, subset, file, unicodeRange }) => ({ family, weight, subset, file, unicodeRange }));
writeFileSync(
  path.join(root, "packages/core/src/career/cv-fonts.manifest.ts"),
  `${banner}// OFL-1.1 fonts from @fontsource (Inter, Noto Sans, Noto Serif). Coverage is verified against each file's cmap in cv-fonts.test.ts.\nexport const CV_FONT_FACES = ${JSON.stringify(manifest, null, 2)} as const;\n`,
);

let total = 0;
const entries = faces.map((f) => {
  const b64 = readFileSync(f.abs).toString("base64");
  total += b64.length;
  return `  ${JSON.stringify(f.file)}: "data:font/woff2;base64,${b64}",`;
});
writeFileSync(
  path.join(root, "apps/mobile/src/features/career/cv-fonts.generated.ts"),
  `${banner}/** CV font files as data URIs, keyed by CV_FONT_FACES[].file. Pass \`(file) => CV_FONT_DATA[file]\` as the renderer's fonts option. */\nexport const CV_FONT_DATA: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`${faces.length} faces, mobile data URIs ${(total / 1024 / 1024).toFixed(2)} MB`);
