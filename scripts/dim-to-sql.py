#!/usr/bin/env python
"""
Builds the catalog migration from data/dim2026/colleges.json (produced by scripts/dim-extract.py).
usage: python scripts/dim-to-sql.py data/dim2026/colleges.json supabase/migrations/20260101005000_dim_college_catalog.sql
The migration is only written to disk; applying it to a database is a separate, explicit step.
"""
import json, re, sys

LANG = {"Azərbaycan bölməsi": "az", "Rus bölməsi": "ru", "Azərbaycan və rus bölmələri birgə": "az_ru"}


def q(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


def split_heading(h):
    """'<parent> nəzdində <college>' -> (parent text as printed, college name); otherwise (None, heading)."""
    m = re.match(r"^(.*?)\s*nəzdində\s*(.+)$", h)
    if not m:
        return None, h.strip()
    return m.group(1).strip(), m.group(2).strip()


def nominative(parent):
    """Parent as printed is genitive ('...Universitetinin'); drop the genitive suffix only when it is unambiguous."""
    if not parent:
        return None
    return re.sub(r"(nin|nın|nun|nün)$", "", parent) if re.search(r"(Universitetinin|Akademiyasının|Konservatoriyasının|Akademiyasının)$", parent) else parent


def main(src, out):
    data = json.load(open(src, encoding="utf8"))
    recs = data["records"]
    colleges = {}
    for r in recs:
        colleges.setdefault(r["institution"], None)
    lines = []
    w = lines.append
    w("-- DİM 2026/2027: boş qalan yerlər (tam orta təhsil bazasında orta ixtisas təhsili müəssisələri / kolleclər).")
    w("-- Generated by scripts/dim-to-sql.py from data/dim2026/colleges.json (extracted by scripts/dim-extract.py). Do not edit by hand.")
    w("-- Source fields kept verbatim: admission code, specialty name, institution heading, division, seats, tuition, DH, special-ability star, PDF page.")
    w("-- The PDF gives no city, so none is stored. universities is not modified; admission_colleges links to it only on an exact name match.")
    w("""
create table public.admission_sources (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  academic_year text not null,
  publisher text not null,
  page_count integer,
  unique (title, academic_year)
);

create table public.admission_colleges (
  id uuid primary key default gen_random_uuid(),
  source_id uuid not null references public.admission_sources(id) on delete cascade,
  heading text not null,
  parent_institution text,
  college_name text not null,
  university_id uuid references public.universities(id) on delete set null,
  first_page integer,
  unique (source_id, heading)
);

create table public.college_programs (
  id uuid primary key default gen_random_uuid(),
  source_id uuid not null references public.admission_sources(id) on delete cascade,
  college_id uuid not null references public.admission_colleges(id) on delete cascade,
  code text not null check (code ~ '^[0-9]{6}$'),
  specialty text not null check (length(btrim(specialty)) > 0),
  division text,
  language text not null check (language in ('az', 'ru', 'az_ru')),
  study_format text not null check (study_format in ('full_time', 'part_time')),
  seats integer not null check (seats >= 0),
  tuition_azn integer check (tuition_azn is null or tuition_azn > 0),
  state_funded boolean not null,
  special_ability boolean not null default false,
  source_page integer not null,
  needs_verification boolean not null default false,
  unique (source_id, code),
  check (state_funded = (tuition_azn is null))
);
create index college_programs_college_idx on public.college_programs (college_id);
create index college_programs_language_idx on public.college_programs (language, study_format);

alter table public.admission_sources enable row level security;
alter table public.admission_colleges enable row level security;
alter table public.college_programs enable row level security;
create policy admission_sources_read on public.admission_sources for select to anon, authenticated using (true);
create policy admission_colleges_read on public.admission_colleges for select to anon, authenticated using (true);
create policy college_programs_read on public.college_programs for select to anon, authenticated using (true);

-- Hosted Supabase has no default privileges: grant explicitly. Read-only for API roles (catalog is admin/migration managed).
revoke all on table public.admission_sources, public.admission_colleges, public.college_programs from public, anon, authenticated;
grant select on table public.admission_sources, public.admission_colleges, public.college_programs to anon, authenticated;
grant all on table public.admission_sources, public.admission_colleges, public.college_programs to service_role;
""")
    w("insert into public.admission_sources (title, academic_year, publisher, page_count) values")
    w("  ('Orta ixtisas təhsili müəssisələrinin boş qalan yerlərinə tələbə qəbulu (tam orta təhsil bazasında)', '2026/2027', 'Dövlət İmtahan Mərkəzi', 20);")
    sid = "(select id from public.admission_sources where academic_year = '2026/2027')"
    first_page = {}
    for r in recs:
        first_page.setdefault(r["institution"], r["page"])
    w("\ninsert into public.admission_colleges (source_id, heading, parent_institution, college_name, university_id, first_page) values")
    rows = []
    for h in colleges:
        parent, name = split_heading(h)
        nom = nominative(parent)
        link = (
            f"(select u.id from public.universities u where u.institution_type = 'college' and lower(u.name) = lower({q(name)})"
            + (f" and (u.affiliated_with is null or lower(u.affiliated_with) = lower({q(nom)}))" if nom else "")
            + " order by (u.affiliated_with is not null) desc limit 1)"
        )
        rows.append(f"  ({sid}, {q(h)}, {q(parent)}, {q(name)}, {link}, {first_page[h]})")
    w(",\n".join(rows) + ";")
    w("\ninsert into public.college_programs (source_id, college_id, code, specialty, division, language, study_format, seats, tuition_azn, state_funded, special_ability, source_page, needs_verification) values")
    rows = []
    for r in recs:
        cid = f"(select id from public.admission_colleges where heading = {q(r['institution'])})"
        lang = LANG[r["division"]]
        fmt = "full_time" if r["form"] == "Ə" else "part_time"
        bad = bool(r["flags"])
        rows.append(f"  ({sid}, {cid}, {q(r['code'])}, {q(r['specialty'])}, {q(r['division'])}, '{lang}', '{fmt}', {r['seats']}, {r['fee'] if r['fee'] is not None else 'null'}, {'true' if r['state_funded'] else 'false'}, {'true' if r['special_ability'] else 'false'}, {r['page']}, {'true' if bad else 'false'})")
    w(",\n".join(rows) + ";")
    open(out, "w", encoding="utf8").write("\n".join(lines) + "\n")
    print("colleges", len(colleges), "programs", len(recs))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
