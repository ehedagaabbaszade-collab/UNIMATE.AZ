alter table public.universities
  add column if not exists institution_type text not null default 'university' check (institution_type in ('university','college')),
  add column if not exists ownership text not null default 'state' check (ownership in ('state','private')),
  add column if not exists source text not null default 'edu.gov.az' check (source in ('edu.gov.az','wikipedia','user_supplied_unverified')),
  add column if not exists affiliated_with text check (affiliated_with is null or length(btrim(affiliated_with)) between 2 and 200);

